"""Generate kernel.py (the Kaggle code_file) from pipeline.py.

Usage: python build_kernel.py --smoke 5   (smoke run, 5 images per dataset)
       python build_kernel.py --smoke 0   (full run)

kernel.py embeds pipeline.py (zlib+base64) because Kaggle script kernels run without a
usable __file__; it writes the pipeline to /tmp/maskbank/pipeline.py and runs the
data / torch / tf stages in separate subprocesses (TF and torch never share a process).
"""

from __future__ import annotations

import argparse
import base64
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent

LAUNCHER = '''"""UMUD maskbank launcher (generated by kaggle/infer_maskbank/build_kernel.py; source: pipeline.py)."""
import base64
import os
import shutil
import subprocess
import sys
import time
import zlib
from pathlib import Path

SMOKE_LIMIT = {smoke}
PIPELINE_B64 = "{payload}"

TMP = Path("/tmp/maskbank")
PIPELINE = TMP / "pipeline.py"
OUT = Path("/kaggle/working/maskbank")
LOGS = OUT / "logs"
T0 = time.time()


def say(message):
    print(f"[launcher {{time.time() - T0:7.1f}}s] {{message}}", flush=True)


def run(stage, extra_env=None):
    env = dict(os.environ, MASKBANK_SMOKE=str(SMOKE_LIMIT), PYTHONUNBUFFERED="1")
    env.update(extra_env or {{}})
    tag = stage + ("_legacy" if extra_env else "")
    say(f"starting stage {{tag}}")
    started = time.time()
    with (LOGS / f"{{tag}}.log").open("w", encoding="utf-8") as log_file:
        proc = subprocess.Popen([sys.executable, "-u", str(PIPELINE), "--stage", stage],
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
        for line in proc.stdout:
            print(f"[{{tag}}] {{line}}", end="", flush=True)
            log_file.write(line)
        code = proc.wait()
    say(f"stage {{tag}} exit={{code}} seconds={{time.time() - started:.1f}}")
    return code


def main():
    TMP.mkdir(parents=True, exist_ok=True)
    LOGS.mkdir(parents=True, exist_ok=True)
    source = zlib.decompress(base64.b64decode(PIPELINE_B64)).decode("utf-8")
    PIPELINE.write_text(source, encoding="utf-8")
    (OUT / "pipeline_source.py").write_text(source, encoding="utf-8")
    say(f"python={{sys.version.split()[0]}} smoke={{SMOKE_LIMIT}}")
    subprocess.run(["nvidia-smi", "--query-gpu=name,memory.total,driver_version", "--format=csv"], check=False)
    codes = {{"data": run("data")}}
    if not (TMP / "manifest_internal.csv").exists():
        say("manifest missing; aborting")
        return
    codes["torch"] = run("torch")
    codes["tf"] = run("tf")
    if codes["tf"] == 3:
        probe = subprocess.run([sys.executable, "-c", "import tensorflow as tf; print(tf.__version__)"],
                               capture_output=True, text=True)
        version = probe.stdout.strip().split("-")[0]
        major_minor = ".".join(version.split(".")[:2])
        say(f"keras loading failed on tf {{version}}; trying tf_keras~={{major_minor}}.0 legacy keras")
        subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", f"tf_keras~={{major_minor}}.0"], check=False)
        codes["tf_legacy"] = run("tf", {{"TF_USE_LEGACY_KERAS": "1"}})
    say(f"exit codes: {{codes}}")
    summary = OUT / "summary.csv"
    if summary.exists():
        print(summary.read_text(), flush=True)
    for path in sorted(OUT.glob("*.npz")):
        say(f"  {{path.name}} {{path.stat().st_size / 1e6:.1f}} MB")
    shutil.rmtree(TMP / "models", ignore_errors=True)


main()
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--smoke", type=int, default=0)
    args = parser.parse_args()
    source = (HERE / "pipeline.py").read_text(encoding="utf-8")
    payload = base64.b64encode(zlib.compress(source.encode("utf-8"), 9)).decode("ascii")
    (HERE / "kernel.py").write_text(LAUNCHER.format(smoke=args.smoke, payload=payload), encoding="utf-8")
    print(f"wrote kernel.py smoke={args.smoke} payload={len(payload)} chars")


if __name__ == "__main__":
    main()
